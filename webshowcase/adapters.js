export function generatePlaywright(testDef) {
  const testSlug = slug(testDef.test_name);
  const filename = `test_${testSlug}.py`;
  const lines = [`"""
Auto-generated by universal-test-framework's Playwright adapter.
Do not edit by hand -- regenerate from the intermediate test definition
instead, or your changes will be lost on the next generation run.

Run with:  python ${filename}
Target site is read from the TEST_BASE_URL env var (default: http://localhost:8000).
"""
import os
import re
import sys

from playwright.sync_api import sync_playwright, expect

sys.path.insert(0, ${j(".")})  # the real CLI/UI embeds an absolute path to your checkout here
from locator_resolution.playwright_resolver import resolve

BASE_URL = os.environ.get("TEST_BASE_URL", "http://localhost:8000")


def test_${testSlug}(page):
`];

  for (const step of testDef.steps) lines.push(playwrightStep(step));

  lines.push(`

if __name__ == "__main__":
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=os.environ.get("HEADED") != "1")
        page = browser.new_page()
        try:
            test_${testSlug}(page)
            print("PASSED: " + ${j(testDef.test_name)})
        finally:
            browser.close()
`);
  return lines.join("");
}

function playwrightStep(step) {
  const { action, target, value } = step;
  switch (action) {
    case "navigate": return `    page.goto(BASE_URL + ${j(target.value)})\n`;
    case "fill": return `    resolve(page, ${j(target)}).fill(${j(value)})\n`;
    case "click": return `    resolve(page, ${j(target)}).click()\n`;
    case "select": return `    resolve(page, ${j(target)}).select_option(label=${j(value)})\n`;
    case "check": return `    resolve(page, ${j(target)}).check()\n`;
    case "uncheck": return `    resolve(page, ${j(target)}).uncheck()\n`;
    case "assert_visible": return `    expect(resolve(page, ${j(target)})).to_be_visible()\n`;
    case "assert_text": return `    expect(resolve(page, ${j(target)})).to_contain_text(${j(value)})\n`;
    case "assert_url": return `    expect(page).to_have_url(re.compile(re.escape(${j(value)})))\n`;
    default: throw new Error(`PlaywrightAdapter: unsupported action ${action}`);
  }
}

