export function generateSelenium(testDef) {
  const testSlug = slug(testDef.test_name);
  const filename = `test_${testSlug}.py`;
  const lines = [`"""
Auto-generated by universal-test-framework's Selenium adapter.
Do not edit by hand -- regenerate from the intermediate test definition
instead, or your changes will be lost on the next generation run.

Run with:  python ${filename}
Requires: pip install selenium (Selenium Manager auto-downloads a driver
for whichever browser you already have installed -- Chrome or Edge).
Target site is read from the TEST_BASE_URL env var (default: http://localhost:8000).
"""
import os
import sys

from selenium import webdriver
from selenium.webdriver.support.ui import Select, WebDriverWait
from selenium.webdriver.support import expected_conditions as EC

sys.path.insert(0, ${j(".")})  # the real CLI/UI embeds an absolute path to your checkout here
from locator_resolution.selenium_resolver import resolve

BASE_URL = os.environ.get("TEST_BASE_URL", "http://localhost:8000")


def test_${testSlug}(driver):
`];

  for (const step of testDef.steps) lines.push(seleniumStep(step));

  lines.push(`

if __name__ == "__main__":
    options = webdriver.ChromeOptions()
    if os.environ.get("HEADED") != "1":
        options.add_argument("--headless=new")
    driver = webdriver.Chrome(options=options)
    try:
        test_${testSlug}(driver)
        print("PASSED: " + ${j(testDef.test_name)})
    finally:
        driver.quit()
`);
  return lines.join("");
}

function seleniumStep(step) {
  const { action, target, value } = step;
  switch (action) {
    case "navigate": return `    driver.get(BASE_URL + ${j(target.value)})\n`;
    case "fill": return `    resolve(driver, ${j(target)}).send_keys(${j(value)})\n`;
    case "click": return `    resolve(driver, ${j(target)}).click()\n`;
    case "select": return `    Select(resolve(driver, ${j(target)})).select_by_visible_text(${j(value)})\n`;
    case "check":
      return `    _el = resolve(driver, ${j(target)})\n    if not _el.is_selected(): _el.click()\n`;
    case "uncheck":
      return `    _el = resolve(driver, ${j(target)})\n    if _el.is_selected(): _el.click()\n`;
    case "assert_visible":
      return `    assert resolve(driver, ${j(target)}).is_displayed(), "Expected element to be visible: " + ${j(JSON.stringify(target))}\n`;
    case "assert_text":
      return `    _text = resolve(driver, ${j(target)}).text\n    assert ${j(value)} in _text, "Expected text " + ${j(value)} + ", got: " + _text\n`;
    case "assert_url":
      return `    WebDriverWait(driver, 5).until(EC.url_contains(${j(value)}), "Expected URL to contain " + ${j(value)} + ", got " + driver.current_url)\n`;
    default: throw new Error(`SeleniumAdapter: unsupported action ${action}`);
  }
}

