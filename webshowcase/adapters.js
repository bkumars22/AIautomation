// ---------------------------------------------------------------------
// Cucumber / Gherkin (adapters/cucumber_adapter.py)
// ---------------------------------------------------------------------

function isAction(step) {
  return !step.action.startsWith("assert");
}

function gherkinKeyword(step, isFirst) {
  if (isFirst) return "Given";
  return isAction(step) ? "When" : "Then";
}

function gherkinStepText(step) {
  const { action, target = {}, value } = step;
  const targetType = target.type;
  const hint = target.hint || {};

  switch (action) {
    case "navigate": return `the user navigates to "${target.value}"`;
    case "fill": return `the user enters "${value}" into the "${target.value}" field`;
    case "click": {
      if (targetType === "element_role") return `the user clicks the ${target.role} named "${target.name}"`;
      const noun = targetType === "button_text" ? "button" : "link";
      return `the user clicks the "${target.value}" ${noun}`;
    }
    case "select": return `the user selects "${value}" from the "${target.value}" dropdown`;
    case "check": return `the user checks the "${target.value}" checkbox`;
    case "uncheck": return `the user unchecks the "${target.value}" checkbox`;
    case "assert_visible":
      if (targetType === "element_role") return `the user should see the ${target.role} named "${target.name}"`;
      return `the user should see "${target.value}"`;
    case "assert_text":
      if ("test_id" in hint) return `the element with test id "${hint.test_id}" should show "${value}"`;
      return `the "${target.value}" should show "${value}"`;
    case "assert_url": return `the URL should contain "${value}"`;
    default: throw new Error(`CucumberAdapter: unsupported action ${action}`);
  }
}

export function generateCucumber(testDef) {
  const lines = [`Feature: ${testDef.test_name}`];
  if (testDef.description) lines.push(`  ${testDef.description}`);
  lines.push("", "  Scenario: runs");
  testDef.steps.forEach((step, i) => {
    lines.push(`    ${gherkinKeyword(step, i === 0)} ${gherkinStepText(step)}`);
  });
  lines.push("");
  return lines.join("\n");
}

