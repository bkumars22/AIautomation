function cypressStep(step) {
  const { action, target, value } = step;
  switch (action) {
    case "navigate": return `    cy.visit(${j(target.value)});\n`;
    case "fill": return `    cy.resolveTarget(${j(target)}).clear().type(${j(value)});\n`;
    case "click": return `    cy.resolveTarget(${j(target)}).click();\n`;
    case "select": return `    cy.resolveTarget(${j(target)}).select(${j(value)});\n`;
    case "check": return `    cy.resolveTarget(${j(target)}).check();\n`;
    case "uncheck": return `    cy.resolveTarget(${j(target)}).uncheck();\n`;
    case "assert_visible": return `    cy.resolveTarget(${j(target)}).should("be.visible");\n`;
    case "assert_text": return `    cy.resolveTarget(${j(target)}).should("contain.text", ${j(value)});\n`;
    case "assert_url": return `    cy.url().should("include", ${j(value)});\n`;
    default: throw new Error(`CypressAdapter: unsupported action ${action}`);
  }
}

