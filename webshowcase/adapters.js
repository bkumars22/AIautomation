/**
 * Client-side ports of this project's Python adapters, for the static
 * GitHub Pages showcase (webshowcase/) — pure code generation only, no
 * server, no real browser execution. These mirror adapters/*.py exactly
 * (same string templates, same per-action switch); see that Python
 * source for the authoritative version this was ported from, and
 * docs/adapters.md for what each one actually does.
 *
 * "Run" isn't offered here on purpose: launching a real browser to
 * execute generated Selenium/Playwright/Cypress code is a server-side
 * operation GitHub Pages architecturally cannot provide. Clone the repo
 * and see docs/getting_started.md to actually run any of this.
 */

// json.dumps() and JSON.stringify() produce identical output for the
// plain strings/objects this format ever uses -- same reasoning as the
// Python adapters' _py()/_js() helpers (avoid repr()-style quote
// collisions), no custom escaper needed here.
function j(value) {
  return JSON.stringify(value);
}

function slug(testName) {
  let s = testName.toLowerCase().replace(/[^a-z0-9]/g, "_");
  while (s.includes("__")) s = s.replace(/__/g, "_");
  return s.replace(/^_+|_+$/g, "");
}

function className(testName) {
  const words = testName.replace(/[^a-zA-Z0-9]/g, " ").split(/\s+/).filter(Boolean);
  return words.map((w) => w[0].toUpperCase() + w.slice(1)).join("") || "GeneratedTest";
}

// ---------------------------------------------------------------------
// Manual test case (generation/manual_case_generator.py)
// ---------------------------------------------------------------------

const TARGET_PHRASE = {
  field_description: (t) => t.value,
  checkbox_description: (t) => `the "${t.value}" checkbox`,
  dropdown_description: (t) => `the "${t.value}" dropdown`,
  button_text: (t) => `the "${t.value}" button`,
  link_text: (t) => `the "${t.value}" link`,
  element_role: (t) => `the ${t.role} named "${t.name}"`,
  page_text: (t) => t.value,
};

function describeTarget(target) {
  const fn = TARGET_PHRASE[target.type];
  return fn ? fn(target) : target.value || "the element";
}

function describeStep(step) {
  const { action, target, value } = step;
  switch (action) {
    case "navigate": return `Go to ${target.value}.`;
    case "fill": return `Enter "${value}" into ${describeTarget(target)}.`;
    case "click": return `Click ${describeTarget(target)}.`;
    case "select": return `Choose "${value}" from ${describeTarget(target)}.`;
    case "check": return `Check ${describeTarget(target)}.`;
    case "uncheck": return `Uncheck ${describeTarget(target)}.`;
    case "assert_visible": return `Verify that ${describeTarget(target)} is visible.`;
    case "assert_text": return `Verify that ${describeTarget(target)} shows "${value}".`;
    case "assert_url": return `Verify the page URL contains "${value}".`;
    default: return `Unrecognized step: ${JSON.stringify(step)}`;
  }
}

export function generateManualCase(testDef) {
  const lines = [`Test Case: ${testDef.test_name}`];
  if (testDef.description) lines.push(testDef.description);
  lines.push("", "Steps:");
  testDef.steps.forEach((step, i) => lines.push(`${i + 1}. ${describeStep(step)}`));
  return lines.join("\n");
}

