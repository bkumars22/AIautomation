function javaStr(value) {
  const escaped = String(value)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r");
  return `"${escaped}"`;
}

function javaMap(obj) {
  if (obj === null || typeof obj !== "object") return javaStr(String(obj));
  const parts = [];
  for (const [key, value] of Object.entries(obj)) {
    parts.push(javaStr(key));
    parts.push(typeof value === "object" && value !== null ? javaMap(value) : javaStr(String(value)));
  }
  if (parts.length === 0) return "Map.<String, Object>of()";
  return `Map.<String, Object>of(${parts.join(", ")})`;
}

